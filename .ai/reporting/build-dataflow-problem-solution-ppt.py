def write_markdown(slides):
    lines = [
        "# DataFlow 数据中台建设汇报",
        "",
        "汇报日期：2026-06-11",
        "",
        "汇报主线：数据源多、数据分散时，如何通过数据中台统一纳管，并解决找数难、治理不可见、用数不放心、政府数据标准转换难。",
        "",
    ]
    for idx, slide in enumerate(slides, start=1):
        lines.append(f"## {idx}. {slide.title}")
        if slide.subtitle:
            lines.extend(["", slide.subtitle])
        if slide.bullets:
            lines.append("")
            for bullet in slide.bullets:
                lines.append(f"- {bullet}")
        if slide.image and slide.image.endswith(".png"):
            lines.extend(["", f"配图：`.ai/qa/dataflow-module-smoke/{slide.image}`"])
        lines.append("")
    base.MD_PATH.write_text("\n".join(lines), encoding="utf-8")


